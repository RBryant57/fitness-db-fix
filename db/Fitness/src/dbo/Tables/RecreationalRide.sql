CREATE TABLE [dbo].[RecreationalRide] (
    [Id]              INT            IDENTITY (1, 1) NOT NULL,
    [Date]            DATETIME       NOT NULL,
    [StartOdometer]   INT            NOT NULL,
    [EndOdometer]     INT            NOT NULL,
    [Distance]        DECIMAL (9, 4) NULL,
    [StartTime]       DATETIME       NOT NULL,
    [EndTime]         DATETIME       NOT NULL,
    [RideTimeHours]   INT            CONSTRAINT [DF_RecreationalRide_RideTimeHours] DEFAULT ((0)) NOT NULL,
    [RideTimeMinutes] INT            CONSTRAINT [DF_RecreationalRide_RideTimeMinutes] DEFAULT ((0)) NOT NULL,
    [RideTimeSeconds] INT            CONSTRAINT [DF_RecreationalRide_RideTimeSeconds] DEFAULT ((0)) NOT NULL,
    [BikeEndTime]     DATETIME       NOT NULL,
    [BikeTimeHours]   INT            CONSTRAINT [DF_RecreationalRide_BikeTimeHours] DEFAULT ((0)) NOT NULL,
    [BikeTimeMinutes] INT            CONSTRAINT [DF_RecreationalRide_BikeTimeMinutes] DEFAULT ((0)) NOT NULL,
    [BikeTimeSeconds] INT            CONSTRAINT [DF_RecreationalRide_BikeTimeSeconds] DEFAULT ((0)) NOT NULL,
    [AverageHR]       INT            NOT NULL,
    [MaxHR]           INT            NOT NULL,
    [AverageCadence]  INT            NOT NULL,
    [ElevationGain]   INT            NOT NULL,
    [MaxSpeed]        DECIMAL (9, 4) NOT NULL,
    [Wind]            NVARCHAR (255) NOT NULL,
    [Temperature]     INT            NOT NULL,
    [Precipitation]   BIT            NOT NULL,
    [BikeId]          INT            NOT NULL,
    [RouteId]         INT            NOT NULL,
    [GpxJsonId]       INT            NULL,
    [Notes]           TEXT           NULL,
    CONSTRAINT [PK_RecreationalRide] PRIMARY KEY CLUSTERED ([Id] ASC),
    CONSTRAINT [CK_AverageRecCadence] CHECK ([AverageCadence]>(0) AND [AverageCadence]<(200)),
    CONSTRAINT [CK_AverageRecHR] CHECK ([AverageHR]>(0) AND [AverageHR]<(220)),
    CONSTRAINT [CK_BikeRecTimeHours] CHECK ([BikeTimeHours]>=(0) AND [BikeTimeHours]<(60)),
    CONSTRAINT [CK_BikeRecTimeMinutes] CHECK ([BikeTimeMinutes]>=(0) AND [BikeTimeMinutes]<(60)),
    CONSTRAINT [CK_BikeRecTimeSeconds] CHECK ([BikeTimeSeconds]>=(0) AND [BikeTimeSeconds]<(60)),
    CONSTRAINT [CK_EndRecOdometer] CHECK ([EndOdometer]>(0)),
    CONSTRAINT [CK_MaxRecHR] CHECK ([MaxHR]>(0) AND [MaxHR]<(220)),
    CONSTRAINT [CK_RideRecMiles] CHECK ([EndOdometer]>[StartOdometer]),
    CONSTRAINT [CK_RideRecTimeHours] CHECK ([RideTimeHours]>=(0) AND [RideTimeHours]<(60)),
    CONSTRAINT [CK_RideRecTimeMinutes] CHECK ([RideTimeMinutes]>=(0) AND [RideTimeMinutes]<(60)),
    CONSTRAINT [CK_RideRecTimeSeconds] CHECK ([RideTimeSeconds]>=(0) AND [RideTimeSeconds]<(60)),
    CONSTRAINT [CK_StartRecOdometer] CHECK ([StartOdometer]>(0)),
    CONSTRAINT [FK_RecreationalRide_Bike] FOREIGN KEY ([BikeId]) REFERENCES [dbo].[Bike] ([Id]),
    CONSTRAINT [FK_RecreationalRide_GpxJson] FOREIGN KEY ([GpxJsonId]) REFERENCES [dbo].[GpxJson] ([Id]) ON DELETE CASCADE,
    CONSTRAINT [FK_RecreationalRide_Route] FOREIGN KEY ([RouteId]) REFERENCES [dbo].[Route] ([Id])
);


GO

